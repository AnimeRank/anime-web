// ==========================================
// IDIOMA ACTUAL
// ==========================================

let idiomaActual =
    localStorage.getItem("animerank-idioma") || "es";


// ==========================================
// CAMBIAR IDIOMA
// ==========================================

function cambiarIdioma(idioma) {

    if (!idiomas[idioma]) {
        idioma = "es";
    }

    idiomaActual = idioma;

    localStorage.setItem(
        "animerank-idioma",
        idiomaActual
    );

    aplicarIdioma();

}


// ==========================================
// APLICAR IDIOMA
// ==========================================

function aplicarIdioma() {

    const textos = idiomas[idiomaActual];

    document.querySelectorAll("[data-idioma]").forEach(elemento => {

        const clave = elemento.dataset.idioma;

        if (textos[clave]) {

            elemento.textContent = textos[clave];

        }

    });

}


// ==========================================
// INICIAR
// ==========================================

document.addEventListener(
    "DOMContentLoaded",
    aplicarIdioma
);
